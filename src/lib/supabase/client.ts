import "react-native-url-polyfill/auto";

import AsyncStorage from "@react-native-async-storage/async-storage";
import { createClient } from "@supabase/supabase-js";
import { AppState } from "react-native";

import { env } from "@/lib/config";

/**
 * Single Supabase client for the mobile app.
 *
 * Session persistence uses AsyncStorage (Supabase's recommended React Native
 * storage adapter). Tokens are refreshed automatically while the app is in the
 * foreground and paused when backgrounded to avoid needless refresh traffic.
 */
export const supabase = createClient(env.supabaseUrl, env.supabaseAnonKey, {
  auth: {
    storage: AsyncStorage,
    autoRefreshToken: true,
    persistSession: true,
    detectSessionInUrl: false,
  },
});

AppState.addEventListener("change", (state) => {
  if (state === "active") {
    supabase.auth.startAutoRefresh();
  } else {
    supabase.auth.stopAutoRefresh();
  }
});
